"""Experiment 10: residual-guided compositional representation discovery.

Bounded symbolic search: fit a baseline, screen a documented feature grammar
against residuals, then evaluate single and pairwise feature additions with BIC.
This is a research prototype, not unrestricted invention or a novelty claim.
Requires Python 3.10+ and NumPy.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import numpy as np

BASE = ("1", "x1", "x2", "x1*x2", "x1^2", "x2^2")
PRIMITIVES = (
    "x1^3", "x2^3", "sin(pi*x1)", "cos(pi*x1)",
    "sin(pi*x2)", "cos(pi*x2)", "sin(pi*x1*x2)",
    "tanh(2*x1*x2)", "abs(x1-x2)", "abs(x1+x2)",
)
# Compositions are generated by multiplying primitive expressions. This is
# intentionally bounded and explicit; no arbitrary program synthesis occurs.
COMPOSITIONS = (
    "x1*sin(pi*x2)", "x2*sin(pi*x1)", "x1*cos(pi*x2)",
    "x2*cos(pi*x1)", "sin(pi*x1)*sin(pi*x2)",
    "sin(pi*x1)*cos(pi*x2)", "cos(pi*x1)*cos(pi*x2)",
    "x1^2*sin(pi*x2)", "x2^2*sin(pi*x1)",
    "x1*tanh(2*x1*x2)", "x2*tanh(2*x1*x2)",
    "x1^2*x2", "x1*x2^2",
)
CANDIDATES = PRIMITIVES + COMPOSITIONS

def feature_values(x: np.ndarray) -> dict[str, np.ndarray]:
    a, b = x[:, 0], x[:, 1]
    z = {
        "1": np.ones(len(x)), "x1": a, "x2": b, "x1*x2": a*b,
        "x1^2": a*a, "x2^2": b*b, "x1^3": a**3, "x2^3": b**3,
        "sin(pi*x1)": np.sin(np.pi*a), "cos(pi*x1)": np.cos(np.pi*a),
        "sin(pi*x2)": np.sin(np.pi*b), "cos(pi*x2)": np.cos(np.pi*b),
        "sin(pi*x1*x2)": np.sin(np.pi*a*b), "tanh(2*x1*x2)": np.tanh(2*a*b),
        "abs(x1-x2)": np.abs(a-b), "abs(x1+x2)": np.abs(a+b),
        "x1*sin(pi*x2)": a*np.sin(np.pi*b),
        "x2*sin(pi*x1)": b*np.sin(np.pi*a),
        "x1*cos(pi*x2)": a*np.cos(np.pi*b),
        "x2*cos(pi*x1)": b*np.cos(np.pi*a),
        "sin(pi*x1)*sin(pi*x2)": np.sin(np.pi*a)*np.sin(np.pi*b),
        "sin(pi*x1)*cos(pi*x2)": np.sin(np.pi*a)*np.cos(np.pi*b),
        "cos(pi*x1)*cos(pi*x2)": np.cos(np.pi*a)*np.cos(np.pi*b),
        "x1^2*sin(pi*x2)": a*a*np.sin(np.pi*b),
        "x2^2*sin(pi*x1)": b*b*np.sin(np.pi*a),
        "x1*tanh(2*x1*x2)": a*np.tanh(2*a*b),
        "x2*tanh(2*x1*x2)": b*np.tanh(2*a*b),
        "x1^2*x2": a*a*b, "x1*x2^2": a*b*b,
    }
    return z

def design(x: np.ndarray, names: tuple[str, ...] | list[str]) -> np.ndarray:
    z = feature_values(x)
    return np.column_stack([z[n] for n in names])

def make_world(rng: np.random.Generator, noise_sd: float = 0.08):
    # Every truth is a composition; none is simply a lone primitive feature.
    truths = (
        "x1*sin(pi*x2)", "x2*sin(pi*x1)", "x1*cos(pi*x2)",
        "sin(pi*x1)*sin(pi*x2)", "sin(pi*x1)*cos(pi*x2)",
        "x1^2*sin(pi*x2)", "x1*tanh(2*x1*x2)", "x1^2*x2",
    )
    truth = truths[int(rng.integers(len(truths)))]
    amp = float(rng.uniform(0.65, 1.35))
    def target(x):
        z = feature_values(x)
        return 0.3*z["x1"] - 0.2*z["x2"] + amp*z[truth]
    return {"truth": truth, "amp": amp, "noise_sd": noise_sd, "target": target}

def fit(x: np.ndarray, y: np.ndarray, names: tuple[str, ...] | list[str]):
    X = design(x, names)
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    residual = y - X @ beta
    n, k = X.shape
    rss = float(residual @ residual)
    bic = n*np.log(max(rss/n, 1e-12)) + k*np.log(max(n, 2))
    return beta, bic, residual

def screen_by_residual(x, residual, pool=CANDIDATES, limit=12):
    """Rank features by absolute residual correlation, excluding constants."""
    z = feature_values(x)
    scored = []
    centered = residual - np.mean(residual)
    norm_r = np.linalg.norm(centered)
    for name in pool:
        v = z[name] - np.mean(z[name])
        denom = norm_r * np.linalg.norm(v)
        score = 0.0 if denom < 1e-12 else abs(float(v @ centered))/denom
        scored.append((score, name))
    scored.sort(reverse=True)
    return [name for _, name in scored[:limit]]

def candidate_models(x, y, screen_limit=12):
    _, _, residual = fit(x, y, BASE)
    screened = screen_by_residual(x, residual, limit=screen_limit)
    models = [BASE]
    models.extend(BASE + (a,) for a in screened)
    # Search two-feature compositions only among residual-supported candidates.
    for i, a in enumerate(screened):
        for b in screened[i+1:]:
            models.append(BASE + (a, b))
    return models

def choose_query(x, y, rng, grid_size=1200):
    models = candidate_models(x, y)
    fitted = []
    for names in models:
        beta, bic, _ = fit(x, y, names)
        fitted.append((names, beta, bic))
    scores = np.array([m[2] for m in fitted])
    weights = np.exp(-0.5*np.clip(scores-scores.min(), 0, 80))
    weights /= weights.sum()
    grid = rng.uniform(-1, 1, size=(grid_size, 2))
    pred = np.column_stack([design(grid, names) @ beta for names, beta, _ in fitted])
    avg = pred @ weights
    disagreement = np.sum(weights[None, :] * (pred-avg[:, None])**2, axis=1)
    return grid[[int(np.argmax(disagreement))]]

def run_arm(world, seed, arm, budget=48, initial=12, test_n=2048):
    rng = np.random.default_rng(seed)
    x = rng.uniform(-1, 1, size=(initial, 2))
    y = world["target"](x) + rng.normal(0, world["noise_sd"], size=initial)
    for _ in range(budget-initial):
        if arm == "active":
            q = choose_query(x, y, rng)
        elif arm in ("passive", "fixed"):
            q = rng.uniform(-1, 1, size=(1, 2))
        else:
            raise ValueError(arm)
        x = np.concatenate((x, q))
        y = np.concatenate((y, world["target"](q) + rng.normal(0, world["noise_sd"], size=1)))
    if arm == "fixed":
        names = BASE
        beta, _, _ = fit(x, y, names)
    else:
        models = candidate_models(x, y)
        fits = [(names, *fit(x, y, names)[:2]) for names in models]
        names, beta, _ = min(fits, key=lambda row: row[2])
    test_rng = np.random.default_rng(seed + 99173)
    tx = test_rng.uniform(-1, 1, size=(test_n, 2))
    mse = float(np.mean((world["target"](tx) - design(tx, names) @ beta)**2))
    return {"arm": arm, "true_composition": world["truth"],
            "selected_features": list(names),
            "recovered_true_composition": world["truth"] in names,
            "test_mse": mse, "observations": len(x)}

def run_benchmark(worlds=100, budget=48, initial=12, seed=20261017):
    rows = []
    for i in range(worlds):
        s = seed + i*1009
        world = make_world(np.random.default_rng(s))
        for arm in ("fixed", "passive", "active"):
            rows.append({"seed": s, **run_arm(world, s, arm, budget, initial)})
    summary = {}
    for arm in ("fixed", "passive", "active"):
        group = [r for r in rows if r["arm"] == arm]
        summary[arm] = {
            "mean_test_mse": float(np.mean([r["test_mse"] for r in group])),
            "median_test_mse": float(np.median([r["test_mse"] for r in group])),
            "composition_recovery_rate": float(np.mean([r["recovered_true_composition"] for r in group])),
            "n_worlds": len(group)}
    paired = {}
    for s in sorted({r["seed"] for r in rows}):
        paired[s] = {r["arm"]: r for r in rows if r["seed"] == s}
    rng = np.random.default_rng(10010)
    contrasts = {}
    for left, right in (("passive", "active"), ("fixed", "passive"), ("fixed", "active")):
        d = np.array([v[left]["test_mse"]-v[right]["test_mse"] for v in paired.values()])
        boot = np.array([np.mean(rng.choice(d, size=len(d), replace=True)) for _ in range(3000)])
        contrasts[f"{left}_minus_{right}"] = {
            "mean_mse_difference": float(np.mean(d)),
            "bootstrap_95_ci": [float(np.quantile(boot, .025)), float(np.quantile(boot, .975))],
            "left_lower_error_worlds": int(np.sum(d < 0)),
            "right_lower_error_worlds": int(np.sum(d > 0))}
    return {"config": {"worlds": worlds, "budget": budget, "initial": initial, "seed": seed, "noise_sd": .08},
            "summary": summary, "contrasts": contrasts, "rows": rows}

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--worlds", type=int, default=100)
    p.add_argument("--budget", type=int, default=48)
    p.add_argument("--initial", type=int, default=12)
    p.add_argument("--seed", type=int, default=20261017)
    p.add_argument("--out", default="exp10_results.json")
    a = p.parse_args()
    result = run_benchmark(a.worlds, a.budget, a.initial, a.seed)
    Path(a.out).write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({"summary": result["summary"], "contrasts": result["contrasts"]}, indent=2))
    print(f"Wrote {a.out}")

if __name__ == "__main__":
    main()
